package com.mousemanager.core

/**
 * Контракт выполнения действия (D-010, D-028).
 *
 * `true` — действие выполнено или это намеренный no-op ([ActionCode.NONE]);
 * `false` — действие не выполнено: система отказала либо вызов бросил исключение.
 * Реализация не бросает исключений наружу и не повторяет действие; исключения
 * логируются внутри, а запись `ACTION_FAILED` в журнал делает вызывающая сторона
 * (D-027 п. 27.3): клавиша уже поглощена, поэтому `CONSUMED` сохраняется.
 *
 * Вызывается на главном потоке: `AccessibilityService.performGlobalAction` требует
 * main thread. Реализация не обязана быть потокобезопасной.
 *
 * Интерфейс живёт в `core` и не знает про Android: это точка расширения из D-010,
 * позволяющая позже добавить Shizuku- или Intent-диспетчер, не меняя [RemapEngine].
 */
interface ActionDispatcher {

    /** Выполняет [action]; возвращает `false` при отказе, но не бросает исключений. */
    fun dispatch(action: ActionCode): Boolean
}
